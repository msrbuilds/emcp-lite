<?php
/**
 * Editor-side auto-repair for AI-inserted static-save blocks.
 *
 * Some block packs (Kadence Blocks is the canonical case) use a static JS
 * `save()` for every block. Markup we build server-side can never byte-match
 * what that JS produces, so the block editor flags each inserted block with
 * "Attempt recovery" even though the front end renders perfectly and recovery
 * preserves the content (issue documented in the Kadence integration).
 *
 * Instead of replicating each pack's save() in PHP (brittle, per-block work),
 * this class automates the recovery itself: when a post an EMCP tool flagged is
 * opened in the block editor, a small script finds the invalid blocks from the
 * covered namespaces and replaces each with a fresh client-side clone —
 * `createBlock( name, attributes, innerBlocks )`, exactly what the "Attempt
 * Block Recovery" button does — so the markup is regenerated by the block's OWN
 * save() and is canonical by definition, whatever the pack's version. One
 * notice asks the user to click Update; the flag clears on that save.
 *
 * @package EMCP_Tools
 * @since   3.12.2
 */

if ( ! defined( 'ABSPATH' ) ) {
	exit;
}

/**
 * Flags posts needing repair + ships the editor auto-repair script.
 *
 * @since 3.12.2
 */
class EMCP_Tools_Block_Repair {

	/** Post meta flag: this post has AI-inserted blocks the editor should auto-repair. */
	const META = '_emcp_block_repair';

	/** Script handle. */
	const SCRIPT = 'emcp-block-repair';

	/**
	 * Wire hooks. Idempotent.
	 *
	 * @since 3.12.2
	 */
	public static function init(): void {
		add_action( 'enqueue_block_editor_assets', array( __CLASS__, 'maybe_enqueue' ) );
		add_action( 'save_post', array( __CLASS__, 'maybe_clear_flag' ), 10, 2 );
	}

	/**
	 * Marks a post as needing editor-side block repair. Called by the tool that
	 * inserted markup it knows cannot byte-match the pack's JS save().
	 *
	 * @since 3.12.2
	 *
	 * @param int $post_id Post ID.
	 */
	public static function flag( int $post_id ): void {
		if ( $post_id > 0 ) {
			update_post_meta( $post_id, self::META, '1' );
		}
	}

	/**
	 * The block-name namespaces the repair script is allowed to auto-recover.
	 * Scoped so a user's own hand-broken block is never silently rewritten —
	 * only packs we KNOW flag AI-inserted markup as invalid-by-architecture.
	 *
	 * @since 3.12.2
	 *
	 * @return string[] Name prefixes, e.g. [ 'kadence/' ].
	 */
	public static function namespaces(): array {
		$namespaces = apply_filters( 'emcp_tools_block_repair_namespaces', array( 'kadence/' ) );
		return array_values( array_filter( array_map( 'strval', (array) $namespaces ) ) );
	}

	/**
	 * Enqueues the repair script in the block editor, only for flagged posts.
	 *
	 * @since 3.12.2
	 */
	public static function maybe_enqueue(): void {
		$post_id = self::current_editor_post_id();
		if ( ! $post_id || '1' !== (string) get_post_meta( $post_id, self::META, true ) ) {
			return;
		}

		$js  = EMCP_TOOLS_DIR . 'assets/js/block-repair.js';
		$ver = ( defined( 'WP_DEBUG' ) && WP_DEBUG && file_exists( $js ) ) ? (string) filemtime( $js ) : EMCP_TOOLS_VERSION;

		wp_enqueue_script(
			self::SCRIPT,
			EMCP_TOOLS_URL . 'assets/js/block-repair.js',
			array( 'wp-blocks', 'wp-data', 'wp-dom-ready', 'wp-notices', 'wp-i18n' ),
			$ver,
			true
		);
		wp_localize_script(
			self::SCRIPT,
			'emcpBlockRepair',
			array(
				'namespaces' => self::namespaces(),
			)
		);
	}

	/**
	 * Clears the flag once the post is genuinely re-saved from the editor —
	 * after the auto-repair ran, the editor's serializer wrote canonical markup,
	 * so future loads have nothing to repair. Autosaves and revisions are
	 * ignored: they don't rewrite the real post_content, and clearing on one
	 * would skip the repair on the next real open.
	 *
	 * The MCP add path sets the flag AFTER its own wp_update_post(), so this
	 * hook (which that update also fires) never eats a fresh flag.
	 *
	 * @since 3.12.2
	 *
	 * @param int      $post_id Post ID.
	 * @param \WP_Post $post    Post object.
	 */
	public static function maybe_clear_flag( $post_id, $post = null ): void {
		$clear = self::should_clear(
			(bool) wp_is_post_revision( $post_id ),
			(bool) wp_is_post_autosave( $post_id ),
			defined( 'DOING_AUTOSAVE' ) && DOING_AUTOSAVE,
			defined( 'REST_REQUEST' ) && REST_REQUEST
		);
		if ( $clear && '1' === (string) get_post_meta( $post_id, self::META, true ) ) {
			delete_post_meta( $post_id, self::META );
		}
	}

	/**
	 * Pure decision: does this save invalidate the repair flag? Only a real
	 * (non-revision, non-autosave) save arriving over the REST API — the block
	 * editor's own save, whose serializer wrote canonical markup. Anything else
	 * (our MCP writes, wp-cli, imports, autosaves) must keep the flag, or the
	 * repair would be skipped on the next real editor open.
	 *
	 * @since 3.12.2
	 *
	 * @param bool $is_revision    Save is a revision write.
	 * @param bool $is_autosave    Save is an autosave post.
	 * @param bool $doing_autosave DOING_AUTOSAVE request.
	 * @param bool $is_rest        REST_REQUEST request.
	 * @return bool
	 */
	public static function should_clear( bool $is_revision, bool $is_autosave, bool $doing_autosave, bool $is_rest ): bool {
		if ( $is_revision || $is_autosave || $doing_autosave ) {
			return false;
		}
		return $is_rest;
	}

	/**
	 * The post being edited in the current block-editor screen, if any.
	 *
	 * @since 3.12.2
	 *
	 * @return int
	 */
	private static function current_editor_post_id(): int {
		if ( isset( $_GET['post'] ) ) { // phpcs:ignore WordPress.Security.NonceVerification.Recommended
			return absint( $_GET['post'] ); // phpcs:ignore WordPress.Security.NonceVerification.Recommended
		}
		$post = get_post();
		return $post ? (int) $post->ID : 0;
	}
}
